package com.bridgelabz.quantitymeasurement.repository;

import com.bridgelabz.quantitymeasurement.model.MeasurementRecord;
import java.sql.*;
import java.util.ArrayList;
import java.util.List;

public class JdbcMeasurementRepository implements MeasurementRepository {
    private final String url;

    public JdbcMeasurementRepository(String url) {
        this.url = url;
        String sql = "CREATE TABLE IF NOT EXISTS measurements (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, operation VARCHAR(40) NOT NULL, result DOUBLE PRECISION NOT NULL, unit VARCHAR(40) NOT NULL)";
        try (Connection connection = connect(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        } catch (SQLException e) {
            throw new IllegalStateException("Could not create measurements table", e);
        }
    }

    private Connection connect() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }

    public MeasurementRecord save(String operation, double result, String unit) {
        String sql = "INSERT INTO measurements (operation, result, unit) VALUES (?, ?, ?)";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, operation);
            statement.setDouble(2, result);
            statement.setString(3, unit);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                keys.next();
                return new MeasurementRecord(keys.getLong(1), operation, result, unit);
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Could not save measurement", e);
        }
    }

    public List<MeasurementRecord> findAll() {
        List<MeasurementRecord> records = new ArrayList<>();
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement("SELECT id, operation, result, unit FROM measurements ORDER BY id");
             ResultSet rows = statement.executeQuery()) {
            while (rows.next()) {
                records.add(new MeasurementRecord(rows.getLong("id"), rows.getString("operation"),
                        rows.getDouble("result"), rows.getString("unit")));
            }
            return records;
        } catch (SQLException e) {
            throw new IllegalStateException("Could not load measurements", e);
        }
    }
}
